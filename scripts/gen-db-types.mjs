// Generates src/types/database.ts from the migrations, without Docker.
// It applies tests/db/supabase-stubs.sql + supabase/migrations/*.sql to an in-memory PGlite
// database and introspects the `public` schema, emitting the same shape as `supabase gen types`.
// Once a real Supabase project exists you can switch to:
//   npx supabase gen types typescript --project-id <id> --schema public > src/types/database.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const db = await PGlite.create();
await db.exec(readFileSync(path.join(root, "tests/db/supabase-stubs.sql"), "utf8"));
for (const file of readdirSync(path.join(root, "supabase/migrations")).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(path.join(root, "supabase/migrations", file), "utf8"));
}

const q = async (sql, params = []) => (await db.query(sql, params)).rows;

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`);
const enumNames = new Set(enums.map((e) => e.name));

const scalar = {
  uuid: "string", text: "string", varchar: "string", bpchar: "string", citext: "string", date: "string",
  timestamptz: "string", timestamp: "string", time: "string", timetz: "string", interval: "string", inet: "string",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number", oid: "number",
  bool: "boolean", json: "Json", jsonb: "Json", tsvector: "unknown", tsquery: "unknown", void: "undefined",
  regconfig: "unknown", record: "Json",
};

function tsType(typname) {
  if (typname.startsWith("_")) return `${tsType(typname.slice(1))}[]`;
  if (enumNames.has(typname)) return `Database["public"]["Enums"]["${typname}"]`;
  return scalar[typname] ?? "unknown";
}

const columns = await q(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default, c.is_identity = 'YES' as identity,
         c.is_generated = 'ALWAYS' as generated
  from information_schema.columns c
  join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.column_name`);

const fks = await q(`
  select con.conname, src.relname as table_name, tgt.relname as referenced,
    array(select a.attname from unnest(con.conkey) k join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k order by a.attname) as cols,
    array(select a.attname from unnest(con.confkey) k join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k) as refcols,
    exists (
      select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique
        and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x) = (select array_agg(x order by x) from unnest(con.conkey) x)
    ) as one_to_one
  from pg_constraint con
  join pg_class src on src.oid = con.conrelid join pg_namespace ns on ns.oid = src.relnamespace
  join pg_class tgt on tgt.oid = con.confrelid join pg_namespace nt on nt.oid = tgt.relnamespace
  where con.contype = 'f' and ns.nspname = 'public' and nt.nspname = 'public'
  order by con.conname`);

const functions = await q(`
  select p.proname as name, p.proretset as retset, rt.typname as ret,
    coalesce(p.proargnames, '{}') as argnames,
    coalesce(p.proargmodes::text[], '{}') as argmodes,
    coalesce(array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, n) join pg_type t on t.oid = a.oid order by a.n), '{}') as argtypes,
    p.pronargs as nargs, p.pronargdefaults as ndefaults
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
  where n.nspname = 'public' and rt.typname <> 'trigger'
    and has_function_privilege('service_role', p.oid, 'execute')
  order by p.proname`);

const tables = [...new Set(columns.map((c) => c.table_name))];
const indent = (s, n) => s.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n");

let out = `// Generated by scripts/gen-db-types.mjs from supabase/migrations — do not edit by hand.
// Run \`npm run db:types\` after changing a migration.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const table of tables) {
  const cols = columns.filter((c) => c.table_name === table);
  const row = cols.map((c) => `${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`).join("\n");
  const insert = cols
    .map((c) => {
      if (c.generated) return `${c.column_name}?: never;`;
      const optional = c.nullable || c.has_default || c.identity;
      return `${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`;
    })
    .join("\n");
  const update = cols
    .map((c) => (c.generated ? `${c.column_name}?: never;` : `${c.column_name}?: ${tsType(c.udt_name)}${c.nullable ? " | null" : ""};`))
    .join("\n");
  const rels = fks
    .filter((f) => f.table_name === table)
    .map(
      (f) => `{
  foreignKeyName: "${f.conname}";
  columns: [${f.cols.map((c) => `"${c}"`).join(", ")}];
  isOneToOne: ${f.one_to_one};
  referencedRelation: "${f.referenced}";
  referencedColumns: [${f.refcols.map((c) => `"${c}"`).join(", ")}];
},`,
    )
    .join("\n");
  out += indent(
    `${table}: {
  Row: {
${indent(row, 4)}
  };
  Insert: {
${indent(insert, 4)}
  };
  Update: {
${indent(update, 4)}
  };
  Relationships: [
${indent(rels, 4)}
  ];
};`,
    6,
  ) + "\n";
}
out += `    };
    Views: { [_ in never]: never };
    Functions: {
`;
for (const fn of functions) {
  const inputs = [];
  const outputs = [];
  fn.argtypes.forEach((type, i) => {
    const mode = fn.argmodes[i] ?? "i";
    const name = fn.argnames[i] ?? `arg${i}`;
    if (mode === "i" || mode === "b") inputs.push({ name, type });
    if (mode === "o" || mode === "t" || mode === "b") outputs.push({ name, type });
  });
  const firstDefault = inputs.length - fn.ndefaults;
  const args = inputs.length
    ? `{ ${inputs.map((a, i) => `${a.name}${i >= firstDefault ? "?" : ""}: ${tsType(a.type)} | null`).join("; ")} }`
    : "Record<PropertyKey, never>";
  let returns;
  if (outputs.length) returns = `{ ${outputs.map((o) => `${o.name}: ${tsType(o.type)} | null`).join("; ")} }[]`;
  else returns = `${tsType(fn.ret)}${fn.retset ? "[]" : ""}`;
  out += `      ${fn.name}: { Args: ${args}; Returns: ${returns} };\n`;
}
out += `    };
    Enums: {
${enums.map((e) => `      ${e.name}: ${e.labels.map((l) => `"${l}"`).join(" | ")};`).join("\n")}
    };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicSchema = Database["public"];
export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

writeFileSync(path.join(root, "src/types/database.ts"), out);
console.log(`Wrote src/types/database.ts (${tables.length} tables, ${functions.length} functions, ${enums.length} enums)`);
